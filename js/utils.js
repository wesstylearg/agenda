  /**
   * Helper to get SVG string with size and custom class
   */
  getIcon(name, size = 18, className = '') {
    const raw = this.icons[name] || this.icons.info;
    return raw.replace('<svg', `<svg width="${size}" height="${size}" class="svg-icon ${className}"`);
  },

  /**
   * Generate a secure unique identifier
   */
  generateId() {
    if (typeof crypto !== 'undefined' && crypto.randomUUID) {
      return crypto.randomUUID();
    }
    return 'id-' + Date.now().toString(36) + '-' + Math.random().toString(36).substring(2, 9);
  },

  /**
   * Capitalize first letter of string
   */
  capitalize(str) {
    if (!str) return '';
    return str.charAt(0).toUpperCase() + str.slice(1);
  },

  /**
   * Format a Date into natural Spanish format: "Jueves, 20 de agosto"
   */
  formatDateNatural(dateInput) {
    const d = this.toDateObject(dateInput);
    if (!d || isNaN(d.getTime())) return '';
    
    const dayIndex = (d.getDay() + 6) % 7; // Map 0->Sunday to 6, 1->Monday to 0
    const dayName = this.DAYS_FULL[dayIndex];
    const dayNumber = d.getDate();
    const monthName = this.MONTHS_FULL[d.getMonth()].toLowerCase();
    
    return `${dayName}, ${dayNumber} de ${monthName}`;
  },

  /**
   * Format a Date into short DD/MM/YY format (e.g. 20/08/26)
   */
  formatDateShort(dateInput) {
    const d = this.toDateObject(dateInput);
    if (!d || isNaN(d.getTime())) return '';

    const day = String(d.getDate()).padStart(2, '0');
    const month = String(d.getMonth() + 1).padStart(2, '0');
    const year = String(d.getFullYear()).slice(-2);

    return `${day}/${month}/${year}`;
  },

  /**
   * Format a Date into standard YYYY-MM-DD format for HTML date inputs
   */
  formatDateISO(dateInput) {
    const d = this.toDateObject(dateInput);
    if (!d || isNaN(d.getTime())) return '';

    const year = d.getFullYear();
    const month = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');

    return `${year}-${month}-${day}`;
  },

  /**
   * Safely convert various date inputs to a Date object in local time
   */
  toDateObject(dateInput) {
    if (!dateInput) return null;
    if (dateInput instanceof Date) return new Date(dateInput.getTime());
    if (typeof dateInput === 'string') {
      const parts = dateInput.split('-');
      if (parts.length === 3) {
        return new Date(parseInt(parts[0], 10), parseInt(parts[1], 10) - 1, parseInt(parts[2], 10));
      }
      return new Date(dateInput);
    }
    if (typeof dateInput === 'number') {
      return new Date(dateInput);
    }
    return null;
  },

  /**
   * Check if two dates represent the exact same calendar day
   */
  isSameDay(dateA, dateB) {
    const a = this.toDateObject(dateA);
    const b = this.toDateObject(dateB);
    if (!a || !b) return false;
    return (
      a.getFullYear() === b.getFullYear() &&
      a.getMonth() === b.getMonth() &&
      a.getDate() === b.getDate()
    );
  },

  /**
   * Calculate difference in calendar days between two dates (target - base)
   */
  daysDifference(targetDate, baseDate = new Date()) {
    const target = this.toDateObject(targetDate);
    const base = this.toDateObject(baseDate);
    if (!target || !base) return null;

    const tUTC = Date.UTC(target.getFullYear(), target.getMonth(), target.getDate());
    const bUTC = Date.UTC(base.getFullYear(), base.getMonth(), base.getDate());

    return Math.round((tUTC - bUTC) / (1000 * 60 * 60 * 24));
  },

  /**
   * Convert "HH:MM" string to minutes from 00:00
   */
  timeToMinutes(timeStr) {
    if (!timeStr || typeof timeStr !== 'string') return 0;
    const [hours, minutes] = timeStr.split(':').map(n => parseInt(n, 10) || 0);
    return hours * 60 + minutes;
  },

  /**
   * Convert minutes from 00:00 to "HH:MM" string
   */
  minutesToTime(totalMinutes) {
    const hours = Math.floor(totalMinutes / 60) % 24;
    const minutes = Math.floor(totalMinutes % 60);
    return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}`;
  },

  /**
   * Calculate duration in minutes between "08:00" and "10:00"
   */
  calculateDurationMinutes(startTime, endTime) {
    const start = this.timeToMinutes(startTime);
    const end = this.timeToMinutes(endTime);
    return Math.max(0, end - start);
  },

  /**
   * Escape HTML special characters
   */
  escapeHTML(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }
